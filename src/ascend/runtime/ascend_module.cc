/*!
 * \file ascend_module.cc
 * \brief Runnable tvm_ffi runtime module for the Ascend NPU backend.
 *
 * Mirrors the CUDA runtime module
 * (3rdparty/tvm/src/runtime/cuda/cuda_module.cc) but for Ascend's
 * bisheng/AscendC toolchain. The device codegen (codegen_ascend.cc) emits, for
 * each kernel `K`, an `extern "C"` void __tl_launch_K(void** void_args,
 * uint32_t grid, uint32_t smem, void* stream); that performs the Ascend
 * triple-chevron launch. Only bisheng can compile that launch, so this module
 * lazily bisheng-compiles the AscendC source into a `.so` and dlopens it,
 * resolving `__tl_launch_K` per kernel. The host stub generated by the generic
 * c-host codegen reaches the kernel through `tvm_call_packed`, which resolves
 * to the PackedFunc returned by GetFunction().
 *
 * The module reports kind "asc" (not "c") and the kRunnable property so that
 * tvm.runtime.Executable.jit() treats it as runnable and does not try to gcc-
 * compile the AscendC source as a C source module.
 *
 * Everything here lives under src/ascend so the Ascend backend is
 * self-contained (no edits to tilelang common or 3rdparty/tvm).
 */
#include <dlfcn.h>
#include <tvm/ffi/extra/c_env_api.h>
#include <tvm/ffi/extra/module.h>
#include <tvm/ffi/function.h>
#include <tvm/ffi/reflection/registry.h>
#include <tvm/runtime/base.h>

#include <mutex>
#include <string>
#include <unordered_map>
#include <utility>
#include <vector>

#include "runtime/pack_args.h"
