import os
from pathlib import Path

_REPO_ROOT = Path(__file__).resolve().parents[3]
os.environ.setdefault("XDG_CACHE_HOME", str(_REPO_ROOT / ".cache"))
os.environ.setdefault("TILELANG_CACHE_DIR", str(_REPO_ROOT / ".tilelang_cache"))

import tilelang.language as T
from tilelang import tvm
from tilelang.engine.phase import LowerAndLegalize, OptimizeForTarget, PreLowerSemanticCheck
from tilelang.utils.target import determine_target


@T.prim_func
def simtvf_demo(
    A: T.Buffer((16,), "float32"),
    B: T.Buffer((16,), "float32"),
):
    with T.Kernel(1, threads=128) as _:
        with T.SimtVF(threads=128):
            for i in T.Parallel(16):
                B[i] = A[i] + T.float32(1)


def _collect_simtvf_loops(func: tvm.tir.PrimFunc):
    loops = []

    def _visit(stmt):
        if isinstance(stmt, tvm.tir.For):
            annotations = stmt.annotations
            if annotations is not None and "tl.simt_vf" in annotations:
                loops.append(stmt)

    tvm.tir.stmt_functor.post_order_visit(func.body, _visit)
    return loops


def _contains_parallel_for(stmt: tvm.tir.Stmt) -> bool:
    found = False

    def _visit(node):
        nonlocal found
        if isinstance(node, tvm.tir.For) and node.kind == tvm.tir.ForKind.PARALLEL:
            found = True

    tvm.tir.stmt_functor.post_order_visit(stmt, _visit)
    return found


def _print_stage(title: str, mod: tvm.IRModule):
    print(f"\n===== {title} =====")
    print(mod.script())
    func = mod["simtvf_demo"]
    loops = _collect_simtvf_loops(func)
    print(f"[check] tl.simt_vf loop count = {len(loops)}")
    for idx, loop in enumerate(loops):
        print(
            f"  loop[{idx}] annotations: "
            f"tl.simt_vf={loop.annotations['tl.simt_vf']}, "
            f"tl.simt_vf_threads={loop.annotations['tl.simt_vf_threads']}"
        )


def _find_thread_predicate_hoist_violations(func: tvm.tir.PrimFunc):
    violations = []

    def _is_thread_predicate(expr: tvm.tir.PrimExpr) -> bool:
        found = False

        def _visit(node):
            nonlocal found
            if isinstance(node, tvm.tir.Var):
                # thread var names are typically tx/ty/tz generated by T.Kernel
                if node.name in ("tx", "ty", "tz"):
                    found = True

        tvm.tir.stmt_functor.post_order_visit(expr, _visit)
        return found

    def _walk_stmt(stmt: tvm.tir.Stmt, simtvf_depth: int) -> None:
        if isinstance(stmt, tvm.tir.For):
            is_simtvf = stmt.annotations is not None and "tl.simt_vf" in stmt.annotations
            _walk_stmt(stmt.body, simtvf_depth + (1 if is_simtvf else 0))
            return

        if isinstance(stmt, tvm.tir.IfThenElse):
            if simtvf_depth == 0 and _is_thread_predicate(stmt.condition):
                violations.append(stmt.condition)
            _walk_stmt(stmt.then_case, simtvf_depth)
            if stmt.else_case is not None:
                _walk_stmt(stmt.else_case, simtvf_depth)
            return

        if isinstance(stmt, tvm.tir.SeqStmt):
            for s in stmt.seq:
                _walk_stmt(s, simtvf_depth)
            return

        if isinstance(stmt, tvm.tir.LetStmt):
            _walk_stmt(stmt.body, simtvf_depth)
            return

        if isinstance(stmt, tvm.tir.AttrStmt):
            _walk_stmt(stmt.body, simtvf_depth)
            return

        if isinstance(stmt, tvm.tir.AssertStmt):
            _walk_stmt(stmt.body, simtvf_depth)
            return

        if isinstance(stmt, tvm.tir.BlockRealize):
            _walk_stmt(stmt.block.body, simtvf_depth)
            return

    _walk_stmt(func.body, 0)
    return violations


def main():
    mod = tvm.IRModule({"simtvf_demo": simtvf_demo})
    target = determine_target("ascend", return_object=True)

    _print_stage("Raw PrimFunc", mod)
    raw_simtvf_loops = _collect_simtvf_loops(mod["simtvf_demo"])
    assert raw_simtvf_loops, "raw stage should contain at least one SimtVF loop"
    assert all(
        _contains_parallel_for(loop.body) for loop in raw_simtvf_loops
    ), "SimtVF region should wrap Parallel loops in raw stage"

    with target:
        PreLowerSemanticCheck(mod)
        lowered = LowerAndLegalize(mod, target)
        _print_stage("After LowerAndLegalize", lowered)
        lowered_loops = _collect_simtvf_loops(lowered["simtvf_demo"])
        assert lowered_loops, "LowerAndLegalize should keep SimtVF annotation"
        assert all(
            int(loop.annotations["tl.simt_vf_threads"]) == 128 for loop in lowered_loops
        ), "LowerAndLegalize should preserve tl.simt_vf_threads"

        optimized = OptimizeForTarget(lowered, target)
        _print_stage("After OptimizeForTarget", optimized)
        optimized_loops = _collect_simtvf_loops(optimized["simtvf_demo"])
        assert optimized_loops, "OptimizeForTarget should keep SimtVF annotation"
        assert all(
            int(loop.annotations["tl.simt_vf_threads"]) == 128 for loop in optimized_loops
        ), "OptimizeForTarget should preserve tl.simt_vf_threads"
        violations = _find_thread_predicate_hoist_violations(optimized["simtvf_demo"])
        assert (
            not violations
        ), f"thread predicate should not be hoisted outside SimtVF on ascend, got: {violations}"

    print("\n[ok] Ascend SimtVF structure/annotations and hoist boundary checks passed.")


if __name__ == "__main__":
    main()
